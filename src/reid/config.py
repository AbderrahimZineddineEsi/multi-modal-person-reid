class Config(_Section):
    """Root configuration."""

    paths: PathsCfg = Field(default_factory=PathsCfg)
    runtime: RuntimeCfg = Field(default_factory=RuntimeCfg)
    detection: DetectionCfg = Field(default_factory=DetectionCfg)
    quality: QualityCfg = Field(default_factory=QualityCfg)
    tracking: TrackingCfg = Field(default_factory=TrackingCfg)
    body_reid: BodyReidCfg = Field(default_factory=BodyReidCfg)
    tracklets: TrackletsCfg = Field(default_factory=TrackletsCfg)
    face: FaceCfg = Field(default_factory=FaceCfg)
    association: AssociationCfg = Field(default_factory=AssociationCfg)
    consolidation: ConsolidationCfg = Field(default_factory=ConsolidationCfg)
    search: SearchCfg = Field(default_factory=SearchCfg)
    render: RenderCfg = Field(default_factory=RenderCfg)

    @property
    def data_dir(self) -> Path:
        """``paths.data_dir`` as an expanded :class:`Path`."""
        return Path(self.paths.data_dir).expanduser()

    def to_json(self) -> str:
        """Serialize for storage in ``runs.config_json``."""
        return self.model_dump_json()


# --------------------------------------------------------------------------- cameras


class CameraSpec(_Section):
    """One camera (video file) of a camera set."""

    id: str = _f(..., "Unique camera id, e.g. 'cam_01'.", min_length=1)
    name: str = _f("", "Display name (defaults to the id).")
    video_path: str = _f(..., "Path to the source video (referenced, never copied).")
    start_ts: float = _f(0.0, "Epoch seconds of frame 0; 0 on all cameras means 'synchronized'.")
    is_face_cam: bool = _f(False, "Run face detection/embedding on this camera.")
    fps: float | None = _f(None, "Override the fps read from the video file.", gt=0)
    homography: list[list[float]] | None = _f(None, "Optional 3x3 image-to-floor homography.")
    background: str | None = _f(
        None, "Optional background image for heatmaps (default: first frame)."
    )

    @model_validator(mode="after")
    def _default_name(self) -> CameraSpec:
        if not self.name:
            self.name = self.id
        return self

    @field_validator("homography")
    @classmethod
    def _check_h(cls, v: list[list[float]] | None) -> list[list[float]] | None:
        if v is not None and (len(v) != 3 or any(len(r) != 3 for r in v)):
            raise ValueError("homography must be 3x3")
        return v


class TopologyEdge(_Section):
    """Minimum plausible transit time between two cameras."""

    src: str = _f(..., "Source camera id.", validation_alias=AliasChoices("src", "from"))
    dst: str = _f(..., "Destination camera id.", validation_alias=AliasChoices("dst", "to"))
    min_transit_s: float = _f(..., "Minimum seconds to get from src to dst.", ge=0)
    symmetric: bool = _f(True, "Apply the same constraint in the reverse direction.")


class CameraSet(_Section):
    """A set of cameras processed into one shared identity space."""

    cameras: list[CameraSpec] = _f(..., "The cameras.", min_length=1)
    topology: list[TopologyEdge] = _f([], "Optional per-pair minimum transit times.")

    @model_validator(mode="after")
    def _validate(self) -> CameraSet:
        ids = [c.id for c in self.cameras]
        if len(set(ids)) != len(ids):
            raise ValueError(f"duplicate camera ids: {ids}")
        for e in self.topology:
            for cid in (e.src, e.dst):
                if cid not in ids:
                    raise ValueError(f"topology references unknown camera {cid!r}")
        return self

    def get(self, camera_id: str) -> CameraSpec:
        """Return the camera with this id (KeyError if absent)."""
        for c in self.cameras:
            if c.id == camera_id:
                return c
        raise KeyError(camera_id)

    def min_transit(self, src: str, dst: str) -> float | None:
        """Minimum transit seconds from ``src`` to ``dst`` or None if unconstrained."""
        for e in self.topology:
            if (e.src, e.dst) == (src, dst) or (e.symmetric and (e.dst, e.src) == (src, dst)):
                return e.min_transit_s
        return None


# --------------------------------------------------------------------------- loading


def deep_merge(base: dict[str, Any], extra: dict[str, Any]) -> dict[str, Any]:
    """Return ``base`` recursively updated with ``extra`` (inputs are not mutated)."""
    out = copy.deepcopy(base)
    for k, v in extra.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict):
            out[k] = deep_merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def expand_dotted(overrides: dict[str, Any]) -> dict[str, Any]:
    """Turn ``{"a.b": 1, "c": {"d": 2}}`` into nested dicts, merging as it goes."""
    out: dict[str, Any] = {}
    for key, value in overrides.items():
        if isinstance(value, dict):
            value = expand_dotted(value)
        node: dict[str, Any] = {}
        cur = node
        parts = key.split(".")
        for p in parts[:-1]:
            cur[p] = {}
            cur = cur[p]
        cur[parts[-1]] = value
        out = deep_merge(out, node)
    return out


def _read_yaml(path: str | Path) -> dict[str, Any]:
    with open(Path(path).expanduser(), encoding="utf-8") as fh:
        data = yaml.safe_load(fh)
    if data is None:
        return {}
    if not isinstance(data, dict):
        raise ValueError(f"{path}: top level must be a mapping")
    return data


def preset_path(preset: str | Path) -> Path:
    """Resolve a preset name (``lite``) or YAML path to a file.

    Names are looked up in ``<package>/presets`` (wheel install), then in the repository's
    ``configs/presets`` (editable install), then in ``./configs/presets``.
    """
    p = Path(preset).expanduser()
    if p.suffix in (".yaml", ".yml") and p.exists():
        return p
    here = Path(__file__).resolve()
    for root in (
        here.parent / "presets",
        here.parents[2] / "configs" / "presets",
        Path("configs/presets"),
    ):
        cand = root / f"{preset}.yaml"
        if cand.exists():
            return cand
    raise FileNotFoundError(f"unknown preset {preset!r}")


def load_config(
    path: str | Path | None = None,
    overrides: dict[str, Any] | None = None,
    preset: str | Path | None = None,
) -> Config:
    """Load a :class:`Config`.

    Precedence (lowest to highest): model defaults, ``preset`` (``configs/presets/<name>.yaml``),
    YAML file at ``path`` (partial files are fine, they are deep-merged), ``overrides`` (nested
    dicts and/or dotted keys such as ``{"association.min_cos": 0.8}``). Unknown keys raise
    ``pydantic.ValidationError``.
    """
    data: dict[str, Any] = {}
    if preset is not None:
        data = expand_dotted(_read_yaml(preset_path(preset)))
    if path is not None:
        data = deep_merge(data, expand_dotted(_read_yaml(path)))
    if overrides:
        data = deep_merge(data, expand_dotted(overrides))
    return Config.model_validate(data)


def load_cameras(path: str | Path) -> CameraSet:
    """Load a camera set YAML (``cameras:`` list and optional ``topology:``).

    Relative ``video_path`` / ``background`` values are kept as written (relative to the
    working directory); ``~`` is expanded.
    """
    cs = CameraSet.model_validate(_read_yaml(path))
    for c in cs.cameras:
        c.video_path = str(Path(c.video_path).expanduser())
        if c.background:
            c.background = str(Path(c.background).expanduser())
    return cs
