"""Configuration models, YAML loading and overrides.

``Config`` is the single source of truth for every tunable parameter. Defaults live in the
pydantic models below (each field carries a description) and are mirrored in
``configs/default.yaml``, which is generated by :func:`reid.config_yaml.render_default_yaml`
and verified by the test-suite.
"""

from __future__ import annotations

import copy
from pathlib import Path
from typing import Any, Literal

import yaml
from pydantic import AliasChoices, BaseModel, ConfigDict, Field, field_validator, model_validator


class _Section(BaseModel):
    """Base for config sections: unknown keys are errors (typo protection)."""

    model_config = ConfigDict(extra="forbid", validate_assignment=True)


def _f(default: Any, desc: str, **kw: Any) -> Any:
    return Field(default=default, description=desc, **kw)


